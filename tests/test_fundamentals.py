"""Tests for fundamentals.py on synthetic financials (no network).

Covers: label extraction, Piotroski 9 tests, Altman Z, DCF, and graceful
None handling when fields are missing.
"""
import unittest

import fundamentals as F


def _rows(pairs):
    return [{"label": label, "value": value} for label, value in pairs]


def _report(year, bs, ic, cf):
    return {"year": year, "form": "10-K",
            "report": {"bs": _rows(bs), "ic": _rows(ic), "cf": _rows(cf)}}


def good_years():
    cur = _report(2025,
        [("Total current assets", 500),
         ("Term debt", 100),  # current portion, BEFORE the total row
         ("Total current liabilities", 250),
         ("Term debt", 300),  # non-current: the one AFTER the total row
         ("Total non-current liabilities", 550),
         ("Total liabilities", 800),
         ("Total assets", 2000),
         ("Accumulated deficit", 600),
         ("Cash and cash equivalents", 200),
         ("Common stock, shares outstanding (in shares)", 100)],
        [("Net sales", 1000), ("Gross margin", 400),
         ("Operating income", 200), ("Net income", 150)],
        [("Cash generated by operating activities", 250),
         ("Payments for acquisition of property, plant and equipment", -50)])
    prev = _report(2024,
        [("Total current assets", 450), ("Total current liabilities", 260),
         ("Term debt", 350),
         ("Total non-current liabilities", 590),
         ("Total liabilities", 850),
         ("Total assets", 1900),
         ("Accumulated deficit", 480),
         ("Cash and cash equivalents", 150),
         ("Common stock, shares outstanding (in shares)", 100)],
        [("Net sales", 900), ("Gross margin", 340),
         ("Operating income", 180), ("Net income", 120)],
        [("Cash generated by operating activities", 200),
         ("Payments for acquisition of property, plant and equipment", -50)])
    return cur, prev


class TestExtract(unittest.TestCase):
    def test_fields(self):
        cur, _ = good_years()
        e = F.extract_annual(cur)
        self.assertEqual(e["year"], 2025)
        self.assertEqual(e["revenue"], 1000)
        self.assertEqual(e["net_income"], 150)
        self.assertEqual(e["total_assets"], 2000)
        self.assertEqual(e["lt_debt"], 300)  # non-current Term debt, not 100
        self.assertEqual(e["fcf"], 200)      # 250 + (-50)
        self.assertEqual(e["shares"], 100)

    def test_missing_everything_is_none(self):
        e = F.extract_annual(_report(2025, [], [], []))
        self.assertIsNone(e["revenue"])
        self.assertIsNone(e["fcf"])


class TestPiotroski(unittest.TestCase):
    def test_perfect_score(self):
        cur_r, prev_r = good_years()
        cur, prev = F.extract_annual(cur_r), F.extract_annual(prev_r)
        p = F.piotroski(cur, prev)
        self.assertEqual(p["score"], 9)
        self.assertEqual(p["of"], 9)
        self.assertTrue(all(v is True for v in p["tests"].values()))

    def test_partial_data(self):
        cur_r, _ = good_years()
        cur = F.extract_annual(cur_r)
        p = F.piotroski(cur, {})  # no prior year -> most tests None
        self.assertTrue(p["tests"]["net_income_positive"])
        self.assertIsNone(p["tests"]["roa_up"])
        self.assertLess(p["evaluated"], 9)
        # score still defined over evaluable tests
        self.assertIsNotNone(p["score"])

    def test_all_missing(self):
        p = F.piotroski(F.extract_annual(_report(2025, [], [], [])),
                        F.extract_annual(_report(2024, [], [], [])))
        self.assertIsNone(p["score"])
        self.assertEqual(p["evaluated"], 0)


class TestAltman(unittest.TestCase):
    def test_safe_zone(self):
        cur_r, _ = good_years()
        cur = F.extract_annual(cur_r)
        z = F.altman_z(cur, price=50.0)
        # A=.125 B=.3 C=.1 D=6.25 E=.5 -> 5.15
        self.assertAlmostEqual(z["z"], 5.15, places=2)
        self.assertEqual(z["zone"], "safe")

    def test_distress_zone(self):
        cur = {"total_assets": 1000, "current_assets": 100,
               "current_liab": 400, "retained": -500, "ebit": -50,
               "total_liab": 900, "revenue": 300, "shares": 100}
        z = F.altman_z(cur, price=1.0)
        self.assertLess(z["z"], 1.81)
        self.assertEqual(z["zone"], "distress")

    def test_missing_inputs_none(self):
        self.assertIsNone(F.altman_z({"total_assets": 0}, 10.0))
        cur_r, _ = good_years()
        cur = F.extract_annual(cur_r)
        self.assertIsNone(F.altman_z(cur, price=None))  # no market cap


class TestDCF(unittest.TestCase):
    def test_hand_computed(self):
        cur_r, prev_r = good_years()
        cur, prev = F.extract_annual(cur_r), F.extract_annual(prev_r)
        d = F.dcf_fair_value(cur, prev, wacc=0.10, growth=0.10,
                             terminal_growth=0.03)
        # growth == wacc -> each projected FCF discounts to exactly 200.
        # Equity = EV - long-term debt (300) + cash (200); payables and
        # other operating liabilities are NOT subtracted (they used to be:
        # total liabilities 800 -> 33.43).
        self.assertAlmostEqual(d["fair_value"], 38.43, places=1)
        self.assertEqual(d["wacc"], 0.10)

    def test_negative_fcf_none(self):
        cur = {"fcf": -10, "shares": 100, "total_liab": 0, "cash": 0}
        self.assertIsNone(F.dcf_fair_value(cur, None))

    def test_bad_wacc_none(self):
        cur_r, _ = good_years()
        cur = F.extract_annual(cur_r)
        self.assertIsNone(F.dcf_fair_value(cur, None, wacc=0.02,
                                           terminal_growth=0.03))


def _crow(label, concept, value):
    return {"label": label, "concept": concept, "value": value}


def _creport(year, end, bs, ic, cf):
    return {"year": year, "endDate": end, "form": "10-K",
            "report": {"bs": bs, "ic": ic, "cf": cf}}


def crm_like_years():
    """Salesforce-shaped: concepts present, capex labelled 'Capital
    expenditures' as a POSITIVE concept value, diluted shares only in the
    income statement, no single FCF field anywhere."""
    bs = [_crow("Total current assets", "us-gaap_AssetsCurrent", 28_222),
          _crow("Total assets", "us-gaap_Assets", 112_305),
          _crow("Total current liabilities", "us-gaap_LiabilitiesCurrent",
                37_118),
          _crow("Noncurrent debt", "us-gaap_LongTermDebtNoncurrent", 10_439),
          _crow("Total liabilities", "us-gaap_Liabilities", 53_163),
          _crow("Retained earnings",
                "us-gaap_RetainedEarningsAccumulatedDeficit", 22_221),
          _crow("Total stockholders' equity", "us-gaap_StockholdersEquity",
                59_142),
          _crow("Cash and cash equivalents",
                "us-gaap_CashAndCashEquivalentsAtCarryingValue", 7_327)]
    ic = [_crow("Total revenues",
                "us-gaap_RevenueFromContractWithCustomerExcludingAssessedTax",
                41_525),
          _crow("Gross profit", "us-gaap_GrossProfit", 32_255),
          _crow("Income from operations", "us-gaap_OperatingIncomeLoss",
                8_331),
          _crow("Net income", "us-gaap_NetIncomeLoss", 7_457),
          _crow("Shares used in computing diluted net income per share "
                "(in shares)",
                "us-gaap_WeightedAverageNumberOfDilutedSharesOutstanding",
                956)]
    cf = [_crow("Net cash provided by operating activities",
                "us-gaap_NetCashProvidedByUsedInOperatingActivities", 14_996),
          _crow("Capital expenditures",
                "us-gaap_PaymentsToAcquirePropertyPlantAndEquipment", 594)]
    cur = _creport(2025, "2026-01-31 00:00:00", bs, ic, cf)
    prev = _creport(2025, "2025-01-31 00:00:00", bs, ic, cf)
    return cur, prev


class TestExtractConcepts(unittest.TestCase):
    def test_fcf_from_ocf_minus_capex(self):
        cur, _ = crm_like_years()
        e = F.extract_annual(cur)
        self.assertEqual(e["ocf"], 14_996)
        self.assertEqual(e["capex"], 594)
        self.assertEqual(e["fcf"], 14_996 - 594)  # NOT None: the CRM bug

    def test_concept_fields(self):
        cur, _ = crm_like_years()
        e = F.extract_annual(cur)
        self.assertEqual(e["ebit"], 8_331)       # OperatingIncomeLoss, not
        #                                          pre-tax income
        self.assertEqual(e["shares"], 956)       # diluted weighted, from IC
        self.assertEqual(e["equity"], 59_142)
        self.assertEqual(e["lt_debt"], 10_439)   # noncurrent debt concept
        self.assertEqual(e["end_date"], "2026-01-31 00:00:00")

    def test_liabilities_derived_from_assets_minus_equity(self):
        # A 10-K that prints Assets + Equity but no Liabilities total.
        bs = [_crow("Total assets", "us-gaap_Assets", 1000),
              _crow("Total stockholders' equity",
                    "us-gaap_StockholdersEquity", 400),
              _crow("Total current assets", "us-gaap_AssetsCurrent", 300),
              _crow("Total current liabilities",
                    "us-gaap_LiabilitiesCurrent", 200),
              _crow("Retained earnings",
                    "us-gaap_RetainedEarningsAccumulatedDeficit", 150)]
        ic = [_crow("Income from operations", "us-gaap_OperatingIncomeLoss",
                    90),
              _crow("Total revenues",
                    "us-gaap_RevenueFromContractWithCustomerExcludingAssessedTax",
                    800)]
        e = F.extract_annual(_creport(2025, "2025-12-31", bs, ic, []))
        self.assertEqual(e["total_liab"], 600)   # 1000 - 400, derived
        z = F.altman_z(e, industry="Technology")  # Z'' needs the derived TL
        self.assertIsNotNone(z)
        self.assertEqual(z["model"], "Z''")


class TestAltmanModels(unittest.TestCase):
    def _cur(self):
        cur_r, _ = crm_like_years()
        return F.extract_annual(cur_r)

    def test_zpp_for_non_manufacturing(self):
        z = F.altman_z(self._cur(), market_cap=199_536,
                       industry="Technology")
        self.assertEqual(z["model"], "Z''")
        # 6.56*(-.0792)+3.26*(.1979)+6.72*(.0742)+1.05*(59142/53163) ~= 1.79
        self.assertAlmostEqual(z["z"], 1.79, places=2)
        self.assertEqual(z["zone"], "grey")      # 1.1 < z <= 2.6

    def test_original_z_for_manufacturing(self):
        z = F.altman_z(self._cur(), market_cap=199_536,
                       industry="Machinery")
        self.assertEqual(z["model"], "Z")
        self.assertIn(z["zone"], ("safe", "grey", "distress"))
        self.assertIn("E", z["parts"])          # sales term present in Z

    def test_zpp_zone_thresholds(self):
        strong = {"total_assets": 1000, "current_assets": 600,
                  "current_liab": 200, "retained": 400, "ebit": 200,
                  "total_liab": 400, "equity": 600, "revenue": 900,
                  "shares": 100}
        z = F.altman_z(strong, industry="Technology")
        self.assertGreater(z["z"], 2.6)
        self.assertEqual(z["zone"], "safe")
        weak = dict(strong, current_assets=100, current_liab=500,
                    retained=-300, ebit=-100, equity=100, total_liab=900)
        z = F.altman_z(weak, industry="Technology")
        self.assertLess(z["z"], 1.1)
        self.assertEqual(z["zone"], "distress")

    def test_financials_not_valid(self):
        z = F.altman_z(self._cur(), industry="Banking")
        self.assertIsNone(z["z"])
        self.assertIsNone(z["zone"])
        self.assertIn("financials", z["reason"])

    def test_zpp_needs_no_market_cap_or_revenue(self):
        cur = self._cur()
        cur["revenue"] = None
        z = F.altman_z(cur, industry="Technology")  # no price/mcap at all
        self.assertIsNotNone(z)


class TestDCFBlock(unittest.TestCase):
    def test_runs_with_profile_shares(self):
        cur_r, prev_r = crm_like_years()
        cur, prev = F.extract_annual(cur_r), F.extract_annual(prev_r)
        d = F.dcf_block(cur, prev, industry="Technology")
        self.assertIsNotNone(d["fair_value"])
        self.assertEqual(d["base_fcf"], 14_402)
        self.assertIsNone(d["reason"])

    def test_financials_skipped(self):
        cur_r, _ = crm_like_years()
        cur = F.extract_annual(cur_r)
        d = F.dcf_block(cur, None, industry="Insurance")
        self.assertIsNone(d["fair_value"])
        self.assertIn("financials", d["reason"])
        self.assertEqual(d["base_fcf"], 14_402)  # FCF still reported

    def test_negative_fcf_skipped(self):
        cur = {"fcf": -50, "shares": 100, "total_liab": 0, "cash": 0}
        d = F.dcf_block(cur, None)
        self.assertIsNone(d["fair_value"])
        self.assertEqual(d["base_fcf"], -50)
        self.assertIn("negative FCF", d["reason"])

    def test_missing_fcf_reason(self):
        d = F.dcf_block({"fcf": None, "shares": 100}, None)
        self.assertIsNone(d["fair_value"])
        self.assertIsNone(d["base_fcf"])
        self.assertIn("no usable FCF", d["reason"])

    def test_no_shares_reason(self):
        d = F.dcf_block({"fcf": 100, "shares": None}, None)
        self.assertIsNone(d["fair_value"])
        self.assertIn("share count", d["reason"])


